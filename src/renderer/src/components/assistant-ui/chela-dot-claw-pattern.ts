const CLAW_COLUMNS = CLAW_DOT_MASK[0].length;
const CLAW_ROWS = CLAW_DOT_MASK.length;

function dotNoise(row: number, column: number) {
  const value = Math.sin(row * 41.17 + column * 19.31) * 10000;
  return value - Math.floor(value);
}

function getClawPart(row: number, column: number): ChelaClawDotPart {
  if (row < 17 && column > 47) {
    return "upper";
  }

  if (row > 20 && row < 39 && column > 55) {
    return "lower";
  }

  return "body";
}

export const CHELA_CLAW_DOTS = CLAW_DOT_MASK.flatMap((line, row) =>
  Array.from(line).flatMap((char, column) => {
    if (char !== "#") {
      return [];
    }

    const noise = dotNoise(row, column);

    return {
      id: `${row}-${column}`,
      x: (column / (CLAW_COLUMNS - 1)) * 100,
      y: (row / (CLAW_ROWS - 1)) * 100,
      opacity: 0.48 + noise * 0.38,
      delay: Math.round(noise * 1800),
      part: getClawPart(row, column),
    };
  }),
);

export const CHELA_CLAW_PARTS = ["body", "upper", "lower"] as const;

export const CHELA_CLAW_DOTS_BY_PART = CHELA_CLAW_PARTS.reduce(
  (groups, part) => ({
    ...groups,
    [part]: CHELA_CLAW_DOTS.filter((dot) => dot.part === part),
  }),
  {} as Record<ChelaClawDotPart, ChelaClawDot[]>,
);
